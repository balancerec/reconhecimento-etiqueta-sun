from pathlib import Path
import json,uuid,subprocess,hashlib,threading,time
from concurrent.futures import ThreadPoolExecutor
from fastapi import APIRouter,HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel,Field
class ProcessRequest(BaseModel):
 image_id:str
 copy_id:str|None=None
 segmentation_id:str|None=None
 brightness:float=Field(default=0,ge=-80,le=80)
 contrast:float=Field(default=1,ge=.5,le=2)
 saturation:float=Field(default=1,ge=0,le=2)
 sharpness:int=Field(default=35,ge=0,le=100)
 deblur:int=Field(default=20,ge=0,le=100)
 denoise:int=Field(default=15,ge=0,le=100)
 clahe:int=Field(default=25,ge=0,le=100)
def create_router(root,svc,gpu,worker):
 root=Path(root);r=APIRouter(prefix='/api/v270/restoration',tags=['restoration']);jobs={};pool=ThreadPoolExecutor(max_workers=1);joblock=threading.Lock()
 def base(image_id,processing_id):
  svc.photo(image_id)
  if not processing_id.isalnum():raise HTTPException(404,'processing id inválido')
  return root/'data'/'restoration'/image_id/processing_id
 @r.post('/process')
 def process(req:ProcessRequest):
  try:p=svc.photo(req.image_id)
  except KeyError:raise HTTPException(404,'imagem não registrada')
  svc.check_source(p);ident=uuid.uuid4().hex;out=root/'data'/'restoration'/req.image_id/ident;out.mkdir(parents=True);q={'brightness':req.brightness,'contrast':req.contrast,'saturation':req.saturation,'sharpness':req.sharpness,'deblur':req.deblur,'denoise':req.denoise,'clahe':req.clahe};cfg={'root':str(root),'input':p['path'],'out':str(out),'params':q,'id':ident,'image_id':p['id'],'copy_id':req.copy_id,'segmentation_id':req.segmentation_id,'original_sha256':p['sha256']}
  if req.segmentation_id:
   if not req.segmentation_id.isalnum() or not (root/'data/segmentations'/req.image_id/(req.segmentation_id+'.mask.png')).exists():raise HTTPException(422,'segmentação não registrada para esta imagem')
  (out/'config.json').write_text(json.dumps(cfg,indent=2),encoding='utf-8');jid=uuid.uuid4().hex;jobs[jid]={'job_id':jid,'processing_id':ident,'image_id':p['id'],'status':'QUEUED','progress':0}
  def work():
   jobs[jid]['status']='RUNNING';jobs[jid]['pid']=None;started=time.time()
   try:
    proc=subprocess.Popen([str(gpu),str(worker),str(out/'config.json')],stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,creationflags=0x08000000);jobs[jid]['pid']=proc.pid
    try:stdout,stderr=proc.communicate(timeout=900)
    except subprocess.TimeoutExpired:proc.kill();stdout,stderr=proc.communicate();jobs[jid].update(status='TIMED_OUT',error='Worker excedeu limite controlado');(out/'stdout.txt').write_text(stdout);(out/'stderr.txt').write_text(stderr);return
    (out/'stdout.txt').write_text(stdout,encoding='utf-8');(out/'stderr.txt').write_text(stderr,encoding='utf-8');jobs[jid]['exit_code']=proc.returncode
    if proc.returncode:jobs[jid].update(status='FAILED',error='Worker falhou; consulte diagnóstico do job')
    else:jobs[jid].update(status='COMPLETED',progress=100)
   except Exception as ex:jobs[jid].update(status='FAILED',error=type(ex).__name__+': '+str(ex)[:300])
   jobs[jid]['elapsed_seconds']=round(time.time()-started,3)
  pool.submit(work);return jobs[jid]
 @r.get('/jobs/{job_id}')
 def job(job_id):
  if job_id not in jobs:raise HTTPException(404,'job inexistente')
  return jobs[job_id]
 @r.get('/{image_id}/{processing_id}')
 def get(image_id,processing_id):
  f=base(image_id,processing_id)/'result.json'
  if not f.exists():raise HTTPException(404,'processamento inexistente')
  return json.loads(f.read_text())
 @r.get('/{image_id}/{processing_id}/image')
 def image(image_id,processing_id):
  f=base(image_id,processing_id)/'restored.png'
  if not f.exists():raise HTTPException(404,'derivado inexistente')
  return FileResponse(f,media_type='image/png')
 @r.get('/{image_id}/{processing_id}/manifest')
 def manifest(image_id,processing_id):
  d=base(image_id,processing_id);f=d/'result.json'
  if not f.exists():raise HTTPException(404,'manifesto inexistente')
  return {'result':json.loads(f.read_text()),'config':json.loads((d/'config.json').read_text()),'files':{x.name:hashlib.sha256(x.read_bytes()).hexdigest() for x in d.glob('*.png')}}
 @r.post('/compare')
 def compare(body:dict):
  image_id=body.get('image_id');svc.photo(image_id);a=base(image_id,body.get('processing_id'));old=body.get('other_processing_id');b=base(image_id,old) if old else None
  return {'image_id':image_id,'original_sha256':svc.photo(image_id)['sha256'],'processing_id':body.get('processing_id'),'other_processing_id':old,'aligned':True,'difference_metric':'diagnostic only; raw pixel absdiff generated by UI','available':(a/'restored.png').exists() and (not b or (b/'restored.png').exists())}
 return r

